"""Every number in the report comes from the results JSON, not from typing.

    .venv/bin/python tools/make_tables.py               # defaults: the newest runs in results/
    .venv/bin/python tools/make_tables.py --source-results R --supplied-results R2 \\
        --sweep S --out DIR                             # explicit; "none" marks a run as absent

Writes into report/generated/ (by default):
  numbers.tex          \\newcommand macros for inline numbers (\\testacc, \\leakPct, ...)
  table_results.tex    clean test results, source vs supplied split
  table_audit.tex      leakage of the supplied split
  table_sweep.tex      the degradation sweep
  table_threshold.tex  the threshold, chosen on validation, checked on held-out test
  table_plantseg.tex   PlantSeg field leaves (accuracy for black rot only; D16)
The tables are bare `tabular`s: the caption and the float are the author's.

Default sources: the newest Colab re-run under results/colab_*/ if there is one, otherwise
the September 2026 runs in results/source and results/supplied. The audit comes from the
source run's results JSON (or --audit). A source that does not exist yet (the Colab sweep)
gives "[pending: ...]" macros and tables, never a made-up number.

Each file starts with a header: the SHA-256 of every source, of this generator, and of the
file's own body, plus any pending source's search pattern. `src.verify --generated DIR`
fails when any of these no longer match: changed data, a changed generator, a hand edit, or
a pending source that now exists.
"""

