# ---- sources ------------------------------------------------------------------------------

def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def rel(p: Path) -> str:
    try:
        return p.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return p.resolve().as_posix()


def newest(pattern: str) -> Path | None:
    found = sorted(REPO.glob(pattern))
    return found[-1] if found else None


class Sources:
    """The JSON files a generated file was built from, and what is still pending."""

    def __init__(self) -> None:
        self.used: list[Path] = []
        self.pending: list[tuple[str, str]] = []  # (what, glob that would find it)

    def header(self, body: str) -> str:
        lines = ["% GENERATED by tools/make_tables.py. Do not edit: re-run the tool.",
                 f"% generator-sha256: {sha256(GENERATOR)}"]
        lines += [f"% source: {rel(p)} sha256={sha256(p)}" for p in dict.fromkeys(self.used)]
        lines += [f"% pending: {what} glob={g}" for what, g in self.pending]
        lines.append(f"% body-sha256: {hashlib.sha256(body.encode()).hexdigest()}")
        return "\n".join(lines) + "\n"


def resolve(arg: str | None, glob: str, fallback: Path | None) -> tuple[Path | None, str | None]:
    """(path, glob to record if absent). "none" = deliberately absent, nothing to wait for."""
    if arg == "none":
        return None, None
    if arg:
        return Path(arg), None
    found = newest(glob)
    if found:
        return found, None
    if fallback is not None and fallback.exists():
        return fallback, None
    return None, glob


# ---- formatting ---------------------------------------------------------------------------

def f4(x: float) -> str:
    return f"{x:.4f}"


def pct(x: float, nd: int = 1) -> str:
    return f"{x:.{nd}f}\\%"


def sci(x: float) -> str:
    """Two significant figures; powers of ten in LaTeX, not 1.9e-06."""
    if x == 0:
        return "0"
    m, e = f"{x:.1e}".split("e")
    return f"{x:.2g}" if -3 <= int(e) <= 3 else f"${m}\\times 10^{{{int(e)}}}$"


def ci(lo: float, hi: float, nd: int = 3) -> str:
    return f"[{lo:.{nd}f}, {hi:.{nd}f}]"


def num(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def tex_class(c: str) -> str:
    return c.replace("_", " ")


PENDING = "\\pending"


def pending_tabular(what: str, how: str) -> str:
    return ("\\begin{tabular}{l}\n\\toprule\n"
            f"{PENDING}{{{what}}}: {how}\\\\\n\\bottomrule\n\\end{{tabular}}\n")


