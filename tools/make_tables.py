def results_table(src: dict | None, sup: dict | None) -> str:
    def col(r: dict | None, f) -> str:
        return f(r) if r else f"{PENDING}{{run}}"

    def t_label(r: dict | None) -> str:
        if r is None:
            return "LBFGS endpoint $T$"
        return ("LBFGS endpoint $T$ (degenerate: not a fitted temperature)" if r["degenerate"]
                else "Temperature $T$ (fitted on clean validation)")

    rows = [
        ("Test images", lambda r: num(r["n"])),
        ("Test accuracy", lambda r: f4(r["acc"])),
        ("\\quad Wilson 95\\% CI", lambda r: ci(*r["acc_ci"])),
        ("Mean confidence", lambda r: f4(r["conf"])),
        ("ECE (15 bins)", lambda r: f4(r["ece"])),
        (t_label(src if src else sup), lambda r: f"{r['t']:.3g}"),
        ("ECE at that $T$", lambda r: sci(r["ece_t"])),
        ("Epochs run", lambda r: f"{r['epochs']}" + (" (early stop)" if r["early"] else "")),
        ("Training time (min)", lambda r: f"{r['minutes']:.1f}"),
    ]
    if src and sup and src["degenerate"] != sup["degenerate"]:
        rows[5] = ("LBFGS endpoint $T$ (see D1)", rows[5][1])
    body = ["\\begin{tabular}{lrr}", "\\toprule",
            " & \\texttt{source} (leak-free) & \\texttt{supplied} (leaky)\\\\", "\\midrule"]
    body += [f"{name} & {col(src, f)} & {col(sup, f)}\\\\" for name, f in rows]
    body += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(body) + "\n"


def audit_table(a: dict) -> str:
    body = ["\\begin{tabular}{lr}", "\\toprule", "Measure & Value\\\\", "\\midrule",
            f"Images & {num(a['n_images'])}\\\\",
            f"Distinct leaves (originals) & {num(a['n_source_leaves'])}\\\\",
            f"Augmented copies & {num(a['n_augmented'])}\\\\",
            f"Leaves in supplied train / test & {num(a['supplied_train_leaves'])} / "
            f"{num(a['supplied_test_leaves'])}\\\\",
            f"Test leaves also in train & {num(a['test_leaves_also_in_train'])} "
            f"({pct(a['pct_test_leaves_also_in_train'])})\\\\",
            f"Test originals whose leaf is in train & {num(a['n_test_originals_leaf_in_train'])}"
            f" of {num(a['n_test_originals'])} ({pct(a['pct_test_originals_leaf_in_train'])})\\\\",
            "\\midrule", "\\multicolumn{2}{l}{Test leaves also in train, by class}\\\\"]
    body += [f"\\quad {tex_class(c)} & {pct(v)}\\\\"
             for c, v in a["per_class_pct_test_leaves_also_in_train"].items()]
    body += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(body) + "\n"


def _param(corruption: str, p: float) -> str:
    return {"gaussian_blur": f"$\\sigma={p:g}$", "brightness": f"$V{{+}}{p:g}$",
            "darkness": f"$V{{-}}{p:g}$", "occlusion": f"{p * 100:g}\\%"}[corruption]


def sweep_table(sw: dict) -> str:
    body = ["\\begin{tabular}{llllrlrr}", "\\toprule",
            "Corruption & Sev. & Param. & Accuracy [95\\% CI] & Conf. & ECE [95\\% CI] & "
            "ECE ($T_\\mathrm{LBFGS}$) & AURC\\\\",
            " & & & & ($T{=}1$) & ($T{=}1$) & & (max softmax)\\\\", "\\midrule"]
    def line(r: dict, name: str, sev: str, par: str) -> str:
        t1, tl = r["temperature"]["T=1"], r["temperature"]["T_lbfgs"]
        return (f"{name} & {sev} & {par} & {f4(r['accuracy'])} {ci(*r['accuracy_wilson95'])} & "
                f"{f4(t1['mean_confidence'])} & {f4(t1['ece'])} {ci(*t1['ece_bootstrap95'])} & "
                f"{f4(tl['ece'])} & {f4(r['scores']['max_softmax']['aurc'])}\\\\")

    # severity 0 is identical for every corruption (asserted in the sweep): one clean row
    clean = next(r for r in sw["rows"] if r["severity"] == 0)
    body.append(line(clean, "Clean", "--", "--"))
    for c, (label, _) in CORR.items():
        body.append("\\midrule")
        body += [line(r, label, str(r["severity"]), _param(c, r["parameter"]))
                 for r in sw["rows"] if r["corruption"] == c and r["severity"] > 0]
    body += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(body) + "\n"


def threshold_table(sw: dict) -> str:
    th = sw["threshold"]
    body = ["\\begin{tabular}{llrrrrr}", "\\toprule",
            "Score & Target & $t$ (chosen on val.) & Held-out conditions & Mean coverage & "
            "Fully referred & $t$ chosen on test\\\\",
            " & & & meeting target & (test) & conditions & (optimistic)\\\\", "\\midrule"]
    for score, by_t in th["by_score"].items():
        for tgt, r in by_t.items():
            v, te, ins = r["validation"], r["test"], r["in_sample_test"]
            t_ins = f"{ins['threshold']:.4g}" if ins["found"] else "none"
            if not v["found"]:
                body.append(f"{SCORE_NAME[score]} & {tgt} & none & -- & -- & -- & {t_ins}\\\\")
                continue
            n = len(te["per_condition"])
            body.append(f"{SCORE_NAME[score]} & {tgt} & {v['threshold']:.4g} & "
                        f"{n - len(te['below_target'])} of {n} & {pct(100 * te['coverage_mean'])}"
                        f" & {len(te['vacuous_conditions'])} & {t_ins}\\\\")
        body.append("\\midrule")
    body[-1] = "\\bottomrule"
    body.append("\\end{tabular}")
    return "\n".join(body) + "\n"


PS_GROUPS = (("downy_mildew", "Downy", "downy mildew"), ("leaf_spot", "LeafSpot", "leaf spot"),
             ("leafroll", "Leafroll", "leafroll"))


def _top_class(predicted: dict[str, int]) -> str:
    c, k = max(predicted.items(), key=lambda kv: kv[1])
    return f"{tex_class(c)} ({k} of {sum(predicted.values())})"


def plantseg_table(ps: dict) -> str:
    """PlantSeg field leaves (D16). Accuracy exists only for black rot; the other three
    classes are out of distribution, and their accuracy cell says so."""
    def conf_cells(c: dict) -> str:
        nw = pct(100 * c["share_without_warning"]) if "share_without_warning" in c else "--"
        return (f"{f4(c['mean'])} & {f4(c['median'])} & {pct(100 * c['share_at_least']['0.90'])}"
                f" & {nw}")

    body = ["\\begin{tabular}{lrlrrrrl}", "\\toprule",
            "Images & $n$ & Accuracy [95\\% CI] & Mean conf. & Median & "
            "$\\ge 0.9$ & No warning & Most assigned class\\\\", "\\midrule"]
    for key, label in (("black_rot", "PlantSeg black rot leaves"),
                       ("black_rot_usual_framing", "\\quad without close-ups, wide views")):
        a = ps[key]
        body.append(f"{label} & {a['n']} & {f4(a['accuracy'])} {ci(*a['accuracy_wilson95'])} & "
                    f"{conf_cells(a['confidence'])} & {_top_class(a['predicted_class'])}\\\\")
    body.append("\\midrule")
    for g, _, name in PS_GROUPS:
        a = ps["out_of_distribution"][g]
        body.append(f"PlantSeg {name} leaves & {a['n']} & n/a (out of distribution) & "
                    f"{conf_cells(a['confidence'])} & {_top_class(a['predicted_class'])}\\\\")
    body.append("\\midrule")
    for k, label in (("plantvillage_clean", "PlantVillage clean test"),
                     ("plantvillage_most_severe", "PlantVillage most severe corruption")):
        a = ps["references"][k]
        body.append(f"{label} & {a['confidence']['n']} & see Table (sweep) & "
                    f"{conf_cells(a['confidence'])} & --\\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(body) + "\n"


def plantseg_macros(ps: dict | None) -> list[tuple[str, str, str]]:
    names = ["psN", "psBrN", "psBrCorrect", "psBrAcc", "psBrAccCI", "psBrMeanConf", "psBrEce",
             "psBrNoWarning", "psBrSensN", "psBrSensAcc", "psBrSensAccCI", "psThreshold",
             "psCleanMeanConf", "psCleanNoWarning", "psSevereCondition", "psSevereMeanConf",
             "psSevereNoWarning"]
    names += [f"ps{m}{x}" for _, m, _ in PS_GROUPS
              for x in ("N", "MeanConf", "MedianConf", "ShareNinety", "NoWarning")]
    if ps is None:
        return [(n, "\\pending{plantseg}", "") for n in names]

    def nw(c: dict) -> str:
        return pct(100 * c["share_without_warning"]) if "share_without_warning" in c else "--"

    br, sens = ps["black_rot"], ps["black_rot_usual_framing"]
    refs = ps["references"]
    clean, severe = refs["plantvillage_clean"], refs["plantvillage_most_severe"]
    corr, sev = severe["condition"].rsplit("_s", 1)
    m = [("psN", str(br["n"] + sum(ps["out_of_distribution"][g]["n"] for g, _, _ in PS_GROUPS)),
          "PlantSeg leaves analysed, each photograph once"),
         ("psBrN", str(br["n"]), "black rot leaves: SMALL, quote with the interval"),
         ("psBrCorrect", str(br["n_correct"]), ""),
         ("psBrAcc", f4(br["accuracy"]), "black rot leaves, the one class that maps"),
         ("psBrAccCI", ci(*br["accuracy_wilson95"]), "Wilson 95%"),
         ("psBrMeanConf", f4(br["mean_confidence"]), ""),
         ("psBrEce", f4(br["ece"]), "no interval: not valid at this n (D16)"),
         ("psBrNoWarning", nw(br["confidence"]), "share accepted without a warning"),
         ("psBrSensN", str(sens["n"]), "without close-ups, wide views and shoots"),
         ("psBrSensAcc", f4(sens["accuracy"]), ""),
         ("psBrSensAccCI", ci(*sens["accuracy_wilson95"]), ""),
         ("psThreshold", f"{ps['threshold']:.4g}" if ps["threshold"] is not None else "--",
          "max softmax, chosen on validation (D10)"),
         ("psCleanMeanConf", f4(clean["confidence"]["mean"]), "PlantVillage clean, T = 1"),
         ("psCleanNoWarning", nw(clean["confidence"]), ""),
         ("psSevereCondition", f"{CORR[corr][0]}, severity {sev}",
          "lowest-accuracy severity-5 condition"),
         ("psSevereMeanConf", f4(severe["confidence"]["mean"]), ""),
         ("psSevereNoWarning", nw(severe["confidence"]), "")]
    for g, mname, _ in PS_GROUPS:
        a = ps["out_of_distribution"][g]
        c = a["confidence"]
        m += [(f"ps{mname}N", str(a["n"]), "out of distribution: confidence only"),
              (f"ps{mname}MeanConf", f4(c["mean"]), ""),
              (f"ps{mname}MedianConf", f4(c["median"]), ""),
              (f"ps{mname}ShareNinety", pct(100 * c["share_at_least"]["0.90"]),
               "share with confidence >= 0.9"),
              (f"ps{mname}NoWarning", nw(c), "")]
    assert [x[0] for x in m] == names
    return m


def numbers(src: dict | None, sup: dict | None, a: dict | None, sw: dict | None,
            ps: dict | None = None) -> str:
    m: list[tuple[str, str, str]] = []  # (name, value, comment)

    def add(name: str, value: str, comment: str = "") -> None:
        m.append((name, value, comment))

    def pend(names: list[str], what: str) -> None:
        for n in names:
            add(n, f"{PENDING}{{{what}}}")

    run_keys = [("testacc", lambda r: f4(r["acc"]), "test accuracy"),
                ("testaccCI", lambda r: ci(*r["acc_ci"]), "Wilson 95% CI"),
                ("meanconf", lambda r: f4(r["conf"]), "mean max-softmax confidence"),
                ("ececlean", lambda r: f4(r["ece"]), "ECE, 15 bins"),
                ("ntest", lambda r: num(r["n"]), "test images"),
                ("tlbfgs", lambda r: f"{r['t']:.3g}",
                 "LBFGS endpoint T; NOT a fitted temperature when degenerate (D1)"),
                ("tlbfgsdegenerate", lambda r: "yes" if r["degenerate"] else "no",
                 "zero validation errors at the kept checkpoint"),
                ("eceattlbfgs", lambda r: sci(r["ece_t"]), "ECE at the LBFGS endpoint"),
                ("epochsrun", lambda r: str(r["epochs"]), ""),
                ("trainminutes", lambda r: f"{r['minutes']:.1f}", "")]
    for suffix, r in (("", src), ("Supplied", sup)):
        for key, f, c in run_keys:
            name = key + suffix
            if r:
                add(name, f(r), c)
            else:
                pend([name], "run")
    if src:
        sp = src["split"]
        add("ntrain", num(sp["train"]), "source split")
        add("nval", num(sp["val"]), "source split")
        if src["dropped"] is not None:
            add("ndropped", num(src["dropped"]), "augmented copies of val/test leaves discarded")
    else:
        pend(["ntrain", "nval", "ndropped"], "run")

    audit_keys: list[tuple[str, str, Callable[[Any], str]]] = [
                  ("nimages", "n_images", num), ("nleaves", "n_source_leaves", num),
                  ("naugmented", "n_augmented", num),
                  ("nsuppliedtestleaves", "supplied_test_leaves", num),
                  ("nleakleaves", "test_leaves_also_in_train", num),
                  ("leakPct", "pct_test_leaves_also_in_train", pct),
                  ("nsuppliedtestoriginals", "n_test_originals", num),
                  ("nleakoriginals", "n_test_originals_leaf_in_train", num),
                  ("leakOrigPct", "pct_test_originals_leaf_in_train", pct)]
    per_class = {"Black_rot": "leakPctBlackRot", "Esca_(Black_Measles)": "leakPctEsca",
                 "Leaf_blight_(Isariopsis_Leaf_Spot)": "leakPctLeafBlight",
                 "healthy": "leakPctHealthy"}
    if a:
        for name, key, fmt in audit_keys:
            add(name, fmt(a[key]), key)
        for c, name in per_class.items():
            add(name, pct(a["per_class_pct_test_leaves_also_in_train"][c]), c)
    else:
        pend([n for n, _, _ in audit_keys] + list(per_class.values()), "audit")

    sweep_names = ["sweepntest", "sweepnval", "sweepvalerrors", "thresholdValue",
                   "thresholdHeldOutMet", "thresholdCoveragePct", "thresholdReferredPct",
                   "thresholdFullyReferred", "thresholdInSample"]
    sev5 = {c: (f"accSevFive{short}", f"eceSevFive{short}") for c, (_, short) in CORR.items()}
    if sw:
        add("sweepntest", num(sw["n_test"]), "")
        add("sweepnval", num(sw["n_val"]), "")
        add("sweepvalerrors", str(sw["t_lbfgs"]["n_val_errors"]), "clean validation errors")
        r = sw["threshold"]["by_score"]["max_softmax"][f"{sw['threshold']['primary_target']:.2f}"]
        v, te, ins = r["validation"], r["test"], r["in_sample_test"]
        if v["found"]:
            n = len(te["per_condition"])
            add("thresholdValue", f"{v['threshold']:.4g}",
                "max softmax, primary target, chosen on degraded validation")
            add("thresholdHeldOutMet", f"{n - len(te['below_target'])} of {n}",
                "held-out test conditions meeting the target")
            add("thresholdCoveragePct", pct(100 * te["coverage_mean"]), "mean, held-out test")
            add("thresholdReferredPct", pct(100 * te["referred_mean"]), "mean, held-out test")
            add("thresholdFullyReferred", str(len(te["vacuous_conditions"])), "")
        else:
            add("thresholdValue", "none", "no threshold met the target on validation")
            for name in ("thresholdHeldOutMet", "thresholdCoveragePct", "thresholdReferredPct",
                         "thresholdFullyReferred"):
                add(name, "--", "no threshold")
        add("thresholdInSample", f"{ins['threshold']:.4g}" if ins["found"] else "none",
            "chosen on the test images themselves: optimistic, comparison only")
        for row in sw["rows"]:
            if row["severity"] == 5:
                a_name, e_name = sev5[row["corruption"]]
                add(a_name, f4(row["accuracy"]), f"{row['corruption']}, severity 5")
                add(e_name, f4(row["temperature"]["T=1"]["ece"]),
                    f"{row['corruption']}, severity 5, T = 1")
    else:
        pend(sweep_names + [x for pair in sev5.values() for x in pair], "sweep")

    m += plantseg_macros(ps)
    lines = ["\\usepackage{xspace}",
             "\\providecommand{\\pending}[1]{\\textbf{[pending: #1]}\\xspace}"]
    for name, value, comment in m:
        c = f"  % {comment}" if comment else ""
        lines.append(f"\\newcommand{{\\{name}}}{{{value}\\xspace}}{c}")
    return "\n".join(lines) + "\n"


def write(out: Path, name: str, body: str, sources: Sources) -> Path:
    p = out / name
    p.write_text(sources.header(body) + body)
    return p


def build(source: Path | None, supplied: Path | None, sweep: Path | None, out: Path,
          audit: Path | None = None, pending_globs: dict[str, str] | None = None,
          plantseg: Path | None = None) -> list[Path]:
    pending_globs = pending_globs or {}
    out.mkdir(parents=True, exist_ok=True)
    load = (lambda p: json.loads(p.read_text()) if p else None)  # noqa: E731
    res_src, res_sup, sw, ps = load(source), load(supplied), load(sweep), load(plantseg)
    a = load(audit) if audit else (res_src or {}).get("audit")
    src = run_numbers(res_src) if res_src else None
    sup = run_numbers(res_sup) if res_sup else None

    def srcs(*used: tuple[Path | None, str]) -> Sources:
        s = Sources()
        for p, what in used:
            if p is not None:
                s.used.append(p)
            elif what in pending_globs:
                s.pending.append((what, pending_globs[what]))
        return s

    audit_src = audit if audit else source
    written = [
        write(out, "numbers.tex", numbers(src, sup, a, sw, ps),
              srcs((source, "source"), (supplied, "supplied"), (audit_src, "audit"),
                   (sweep, "sweep"), (plantseg, "plantseg"))),
        write(out, "table_results.tex", results_table(src, sup),
              srcs((source, "source"), (supplied, "supplied"))),
        write(out, "table_audit.tex",
              audit_table(a) if a else pending_tabular("audit", "no results JSON with an audit"),
              srcs((audit_src, "audit"))),
        write(out, "table_sweep.tex",
              sweep_table(sw) if sw else pending_tabular(
                  "sweep", "the degradation sweep has not been run yet (HANDOVER.md)"),
              srcs((sweep, "sweep"))),
        write(out, "table_threshold.tex",
              threshold_table(sw) if sw else pending_tabular(
                  "threshold", "comes from the degradation sweep (HANDOVER.md)"),
              srcs((sweep, "sweep"))),
        write(out, "table_plantseg.tex",
              plantseg_table(ps) if ps else pending_tabular(
                  "plantseg", "PlantSeg field leaves come from notebook 04 (HANDOVER.md)"),
              srcs((plantseg, "plantseg"))),
    ]
    return written


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source-results", help="results JSON of the source run ('none' = absent)")
    ap.add_argument("--supplied-results", help="results JSON of the supplied run ('none')")
    ap.add_argument("--sweep", help="sweep JSON of the source run ('none' = absent)")
    ap.add_argument("--audit", help="audit JSON (default: the source run's own audit)")
    ap.add_argument("--plantseg", help="plantseg JSON of the source run ('none' = absent)")
    ap.add_argument("--out", default=str(REPO / "report" / "generated"))
    a = ap.parse_args()
    source, g1 = resolve(a.source_results, SOURCE_GLOB, SEPTEMBER["source"])
    supplied, g2 = resolve(a.supplied_results, SUPPLIED_GLOB, SEPTEMBER["supplied"])
    if a.sweep is None and source is not None:  # the sweep OF the chosen source run
        run_id = json.loads(source.read_text()).get("run_id")  # September runs have none
        own = source.parent / f"sweep_{run_id}.json" if run_id else None
        sweep, g3 = (own, None) if own is not None and own.exists() else (None, SWEEP_GLOB)
    else:
        sweep, g3 = resolve(a.sweep, SWEEP_GLOB, None)
    if a.plantseg is None and source is not None:  # the PlantSeg run OF the chosen source run
        run_id = json.loads(source.read_text()).get("run_id")
        own = source.parent / f"plantseg_{run_id}.json" if run_id else None
        plantseg, g4 = (own, None) if own is not None and own.exists() else (None, PLANTSEG_GLOB)
    else:
        plantseg, g4 = resolve(a.plantseg, PLANTSEG_GLOB, None)
    pending = {w: g for w, g in (("source", g1), ("supplied", g2), ("sweep", g3),
                                 ("plantseg", g4)) if g}
    for what, p in (("source run", source), ("supplied run", supplied), ("sweep", sweep),
                    ("plantseg", plantseg)):
        print(f"{what:13s}: {rel(p) if p else 'PENDING (not available yet)'}")
    for p in build(source, supplied, sweep, Path(a.out), Path(a.audit) if a.audit else None,
                   pending, plantseg):
        print("written ->", rel(p))


if __name__ == "__main__":
    main()
