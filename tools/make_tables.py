def run_numbers(res: dict) -> dict:
    """The clean-test numbers of one run, from either results format (September 2026 or the
    current src.train). The LBFGS endpoint is labelled degenerate when validation had no
    errors at the kept checkpoint: it is then not a fitted temperature (DECISIONS.md D1)."""
    n = int(res["split_sizes"]["test"])
    acc = float(res["test_accuracy"])
    k = round(acc * n)
    assert abs(k / n - acc) < 1e-9, "test accuracy is not k / n for an integer k"
    if "t_lbfgs" in res:
        t, degenerate = res["t_lbfgs"]["t_lbfgs_endpoint"], res["t_lbfgs"]["degenerate"]
        ece_t = res["ece_at_t_lbfgs"]
    else:  # September 2026 format
        t, ece_t = res["temperature"], res["ece_after_temperature"]
        best = [h for h in res["history"] if h["val_loss"] == res["best_val_loss"]][-1]
        degenerate = best["val_acc"] == 1.0
    return {"n": n, "k": k, "acc": acc, "acc_ci": wilson_ci(k, n),
            "conf": float(res["mean_confidence"]), "ece": float(res["ece"]), "t": float(t),
            "degenerate": bool(degenerate), "ece_t": float(ece_t),
            "epochs": int(res["epochs_run"]), "early": bool(res["stopped_early"]),
            "minutes": float(res["minutes"]), "split": res["split_sizes"],
            "dropped": res.get("dropped_augmented_from_eval")}


